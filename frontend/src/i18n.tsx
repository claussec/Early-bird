const DICTS: Record<Lang, Record<Key, string>> = { de: DE, en: EN }
const STORAGE_KEY = 'early-bird.lang'

// Dynamic keys (`risk.${status}`) are allowed; unknown keys render as the key itself.
export type T = (key: Key | (string & {}), vars?: Record<string, string | number>) => string

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'de' || stored === 'en') return stored
  } catch {
    /* per-viewer convenience only */
  }
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en'
}

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: T
  /** Locale for numbers and dates. */
  locale: string
}

const I18n = createContext<Ctx | null>(null)

export function LangProvider({ children, onChange }: { children: ReactNode; onChange?: (l: Lang) => void }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const l = initialLang()
    onChange?.(l)
    return l
  })
  const setLang = useCallback(
    (l: Lang) => {
      try {
        localStorage.setItem(STORAGE_KEY, l)
      } catch {
        /* ignore */
      }
      document.documentElement.lang = l
      onChange?.(l)
      setLangState(l)
    },
    [onChange],
  )
  const value = useMemo<Ctx>(() => {
    const dict = DICTS[lang]
    const t: T = (key, vars) => {
      const text = (dict as Record<string, string>)[key] ?? key
      return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : text
    }
    return { lang, setLang, t, locale: lang === 'de' ? 'de-DE' : 'en-GB' }
  }, [lang, setLang])
  return <I18n.Provider value={value}>{children}</I18n.Provider>
}

export function useI18n(): Ctx {
  const ctx = useContext(I18n)
  if (!ctx) throw new Error('useI18n outside LangProvider')
  return ctx
}

/** Renders a dictionary text that contains <b>…</b> markup (trusted, from this file only). */
export function Rich({ text, className }: { text: string; className?: string }) {
  const parts = text.split(/(<b>.*?<\/b>)/g)
  return (
    <span className={className}>
      {parts.map((p, i) =>
        p.startsWith('<b>') ? (
          <b key={i} className="text-ink-1">
            {p.slice(3, -4)}
          </b>
        ) : (
          p
        ),
      )}
    </span>
  )
}
